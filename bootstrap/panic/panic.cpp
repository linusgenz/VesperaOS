void put_pixel(const Framebuffer* fb, uint32_t x, uint32_t y, uint32_t color) {
    if (x >= fb->width || y >= fb->height) return;
    auto* pixel_ptr = static_cast<uint32_t*>(fb->base_address);
    pixel_ptr[y * fb->pixels_per_scanline + x] = color;
}


void put_char(const Framebuffer* fb, const unsigned char c, const uint32_t x, const uint32_t y, const uint32_t color) {
    if (c == ' ') {
        //space
        return;
    }
    if (c >= 'A' && c <= 'Z') {
        const uint8_t* glyph = simple_font[c - 'A' + 1];
        for (uint32_t row = 0; row < 16; row++) {
            uint8_t row_bits = glyph[row];
            for (uint32_t bit = 0; bit < 8; bit++) {
                if (row_bits & (0x80 >> bit)) {
                    put_pixel(fb, x + bit, y + row, color);
                }
            }
        }
    }
}

void put_string(const Framebuffer* fb, const char* str, const uint32_t x, const uint32_t y, uint32_t color) {
    uint32_t cursor_x = x;
    uint32_t cursor_y = y;
    while (*str) {
        unsigned char c = *str;
        if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
        if (c == '\n') {
            cursor_x = x;
            cursor_y += 16;
        } else {
            put_char(fb, c, cursor_x, cursor_y, color);
            cursor_x += 8;
        }
        str++;
    }
}

[[noreturn]] void panic(const char* panic_msg, Framebuffer* fb) {

    // Text zentrieren, approx.
    uint32_t text_width_1 = 8 * 12; // "KERNEL PANIC"
    uint32_t text_width_2 = 8 * strlen(panic_msg);

    uint32_t x1 = (fb->width - text_width_1) / 2;
    uint32_t x2 = (fb->width - text_width_2) / 2;
    uint32_t y1 = fb->height / 2 - 16;
    uint32_t y2 = y1 + 32;

    put_string(fb, "BOOTSTRAPER PANIC", x1, y1, 0xFFFFFFFF);
    put_string(fb, panic_msg, x2, y2, 0xFFFFFFFF);

    while (true) asm volatile("cli; hlt");
}