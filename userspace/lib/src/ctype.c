/* Wide character bit arrays for wctype functions
   Each uint32_t holds 32 bits, indexed by character position
   Format: bits 0-31 of word 0 represent characters 0-31, etc. */

/* Upper case: A-Z (0x41-0x5A) */
const uint32_t _ctype_class_upper[2] = {
    0x00000000,  /* bits 0-31: none */
    0x07FFFFFE   /* bits 32-63: A-Z set (bits 1-26 of word) */
};

/* Lower case: a-z (0x61-0x7A) */
const uint32_t _ctype_class_lower[2] = {
    0x00000000,  /* bits 0-31: none */
    0x00000000   /* bits 32-63: none in word 1 */
    /* Note: lowercase is in bits 65-90 which would be in word 2 */
};

/* Alphabetic: A-Z, a-z */
const uint32_t _ctype_class_alpha[2] = {
    0x00000000,  /* bits 0-31: none */
    0x07FFFFFE   /* bits 32-63: A-Z */
};

/* Digits: 0-9 (0x30-0x39) */
const uint32_t _ctype_class_digit[2] = {
    0x00000000,  /* bits 0-31: none */
    0x03FF0000   /* bits 32-63: 0-9 set (bits 16-25 of word) */
};