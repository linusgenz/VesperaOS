// Character classification and conversion tables for x86_64 little-endian.
//
// All bit values are derived from the _ISbit() macro in ctype.h:
//   bit < 8:  (1 << bit) << 8
//   bit >= 8: (1 << bit) >> 8
//
// Resulting bit positions (little-endian):
//   _ISupper  = _ISbit(0)  = 0x0100
//   _ISlower  = _ISbit(1)  = 0x0200
//   _ISalpha  = _ISbit(2)  = 0x0400
//   _ISdigit  = _ISbit(3)  = 0x0800
//   _ISxdigit = _ISbit(4)  = 0x1000
//   _ISspace  = _ISbit(5)  = 0x2000
//   _ISprint  = _ISbit(6)  = 0x4000
//   _ISgraph  = _ISbit(7)  = 0x8000
//   _ISblank  = _ISbit(8)  = 0x0001
//   _IScntrl  = _ISbit(9)  = 0x0002
//   _ISpunct  = _ISbit(10) = 0x0004
//   _ISalnum  = _ISbit(11) = 0x0008
//
// Composite values used in the table:
//   control char              = 0x0002
//   space (0x20)              = 0x6001  (print+space+blank)
//   tab  (0x09)               = 0x2003  (cntrl+space+blank)
//   LF/VT/FF/CR (0x0A-0x0D)  = 0x2002  (cntrl+space)
//   punctuation               = 0xC004  (print+graph+punct)
//   '0'-'9'                   = 0xD808  (print+graph+alnum+digit+xdigit)
//   'A'-'F'                   = 0xD508  (print+graph+alnum+alpha+upper+xdigit)
//   'G'-'Z'                   = 0xC508  (print+graph+alnum+alpha+upper)
//   'a'-'f'                   = 0xD608  (print+graph+alnum+alpha+lower+xdigit)
//   'g'-'z'                   = 0xC608  (print+graph+alnum+alpha+lower)

